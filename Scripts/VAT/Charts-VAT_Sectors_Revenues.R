"Dashboard-VAT Sector Revenues"

suppressMessages({

VAT_sectors_revenues_fun <- function(
  forecast_combined_cpa_selected,
  SimulationYear
) {

  # Reporting copy in EUR million ----

  forecast_combined_cpa_selected_display <- forecast_combined_cpa_selected |>
    dplyr::mutate(
      dplyr::across(
        dplyr::any_of(
          c(
            "Businesses_VAT",
            "Households_VAT",
            "NPISH_VAT",
            "Goverment_VAT",
            "Total_VAT"
          )
        ),
        ~ .x / 1000
      )
    )

  # 1. Total VAT ----

  vat_nace_total_plt <- plotly::plot_ly(forecast_combined_cpa_selected_display) |>
    plotly::add_trace(
      x = ~PRODUCT_INDUSTRY_CODE,
      y = ~Total_VAT,
      type = "bar",
      name = ~scenario,
      text = "",
      hoverinfo = "text",
      hovertext = ~paste0(
        PRODUCT_INDUSTRY_NAME,
        "<br>VAT: ",
        format(round(Total_VAT, 1), big.mark = ",", nsmall = 1),
        " EUR million"
      ),
      showlegend = TRUE
    ) |>
    plotly::layout(
      title = list(
        text = paste("Breakdown of VAT by Sector (EUR million),", SimulationYear),
        x = 0.5,
        y = 0.95,
        font = list(size = 14)
      ),
      xaxis = list(
        title = "",
        tickangle = -90,
        tickfont = list(size = 11)
      ),
      yaxis = list(title = "EUR million"),
      legend = list(x = 0.9, y = 0.99),
      barmode = "group",
      annotations = list(
        list(
          x = -0.05,
          y = -0.13,
          text = "Source: WB staff estimation",
          showarrow = FALSE,
          xref = "paper",
          yref = "paper",
          xanchor = "left",
          yanchor = "top",
          font = list(size = 8)
        )
      )
    )

  # 2. Households ----

  vat_nace_hh_plt <- plotly::plot_ly(forecast_combined_cpa_selected_display) |>
    plotly::add_trace(
      x = ~PRODUCT_INDUSTRY_CODE,
      y = ~Households_VAT,
      type = "bar",
      name = ~scenario,
      text = "",
      hoverinfo = "text",
      hovertext = ~paste0(
        PRODUCT_INDUSTRY_NAME,
        "<br>VAT: ",
        format(round(Households_VAT, 1), big.mark = ",", nsmall = 1),
        " EUR million"
      ),
      showlegend = TRUE
    ) |>
    plotly::layout(
      title = list(
        text = paste("VAT Revenues Generated by Households (EUR million),", SimulationYear),
        x = 0.5,
        y = 0.95,
        font = list(size = 14)
      ),
      xaxis = list(
        title = "",
        tickangle = -90,
        tickfont = list(size = 11)
      ),
      yaxis = list(title = "EUR million"),
      legend = list(x = 0.9, y = 0.99),
      barmode = "group",
      annotations = list(
        list(
          x = -0.05,
          y = -0.13,
          text = "Source: WB staff estimation",
          showarrow = FALSE,
          xref = "paper",
          yref = "paper",
          xanchor = "left",
          yanchor = "top",
          font = list(size = 8)
        )
      )
    )

  # 3. Businesses ----

  vat_nace_businesses_plt <- plotly::plot_ly(forecast_combined_cpa_selected_display) |>
    plotly::add_trace(
      x = ~PRODUCT_INDUSTRY_CODE,
      y = ~Businesses_VAT,
      type = "bar",
      name = ~scenario,
      text = "",
      hoverinfo = "text",
      hovertext = ~paste0(
        PRODUCT_INDUSTRY_NAME,
        "<br>VAT: ",
        format(round(Businesses_VAT, 1), big.mark = ",", nsmall = 1),
        " EUR million"
      ),
      showlegend = TRUE
    ) |>
    plotly::layout(
      title = list(
        text = paste("VAT Revenues Generated by Businesses (EUR million),", SimulationYear),
        x = 0.5,
        y = 0.95,
        font = list(size = 14)
      ),
      xaxis = list(
        title = "",
        tickangle = -90,
        tickfont = list(size = 11)
      ),
      yaxis = list(title = "EUR million"),
      legend = list(x = 0.9, y = 0.99),
      barmode = "group",
      annotations = list(
        list(
          x = -0.05,
          y = -0.13,
          text = "Source: WB staff estimation",
          showarrow = FALSE,
          xref = "paper",
          yref = "paper",
          xanchor = "left",
          yanchor = "top",
          font = list(size = 8)
        )
      )
    )

  # 4. Government ----

  vat_nace_gov_plt <- plotly::plot_ly(forecast_combined_cpa_selected_display) |>
    plotly::add_trace(
      x = ~PRODUCT_INDUSTRY_CODE,
      y = ~Goverment_VAT,
      type = "bar",
      name = ~scenario,
      text = "",
      hoverinfo = "text",
      hovertext = ~paste0(
        PRODUCT_INDUSTRY_NAME,
        "<br>VAT: ",
        format(round(Goverment_VAT, 1), big.mark = ",", nsmall = 1),
        " EUR million"
      ),
      showlegend = TRUE
    ) |>
    plotly::layout(
      title = list(
        text = paste("VAT Revenues Generated by Government (EUR million),", SimulationYear),
        x = 0.5,
        y = 0.95,
        font = list(size = 14)
      ),
      xaxis = list(
        title = "",
        tickangle = -90,
        tickfont = list(size = 11)
      ),
      yaxis = list(title = "EUR million"),
      legend = list(x = 0.9, y = 0.99),
      barmode = "group",
      annotations = list(
        list(
          x = -0.05,
          y = -0.13,
          text = "Source: WB staff estimation",
          showarrow = FALSE,
          xref = "paper",
          yref = "paper",
          xanchor = "left",
          yanchor = "top",
          font = list(size = 8)
        )
      )
    )

  list(
    vat_nace_total_plt = vat_nace_total_plt,
    vat_nace_hh_plt = vat_nace_hh_plt,
    vat_nace_businesses_plt = vat_nace_businesses_plt,
    vat_nace_gov_plt = vat_nace_gov_plt
  )
}

})
